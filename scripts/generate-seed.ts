/**
 * Generates supabase/seed.sql and public/demo-vehicles/*.svg from the
 * deterministic demo dataset. Run: npm run db:seed:generate
 * Every seeded advertisement/dealer/review is flagged is_demo = true.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { dealerships, derivatives, equipmentCatalogue, makeSlugForKey, manufacturers, modelsFromCatalogue, slugify } from "../src/data/demo/catalogue";
import { DEMO_REFERENCE_DATE, demoVehicles } from "../src/data/demo/vehicles";
import { renderVehicleSvg, type ArtVariant } from "./vehicle-art";

const root = join(__dirname, "..");
const q = (v: unknown): string =>
  v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const uid = (key: string) => `md5(${q(key)})::uuid`;

const sql: string[] = [
  "-- GENERATED by scripts/generate-seed.ts — DEMONSTRATION DATA ONLY. Do not edit by hand.",
  "-- Dealerships, sellers and listings are fictional and flagged is_demo = true.",
  "begin;",
];

// Demo auth users (private sellers + one owner per dealer). Emails use the reserved example.com domain.
const privateSellers = [...new Set(demoVehicles.filter((v) => v.sellerType === "private").map((v) => v.id))];
for (const id of privateSellers) sql.push(`insert into auth.users (id, email, raw_user_meta_data) values (${uid(`user-${id}`)}, ${q(`seller-${id}@example.com`)}, '{"display_name":"Demo private seller"}');`);
for (const d of dealerships) sql.push(`insert into auth.users (id, email, raw_user_meta_data) values (${uid(`user-${d.id}`)}, ${q(`owner-${d.slug}@example.com`)}, '{"display_name":"Demo dealer owner"}');`);

for (const m of manufacturers) sql.push(`insert into public.manufacturers (id, slug, name, country, is_popular) values (${uid(m.id)}, ${q(m.slug)}, ${q(m.name)}, ${q(m.country)}, ${m.popular});`);
for (const m of modelsFromCatalogue()) sql.push(`insert into public.models (id, manufacturer_id, slug, name) values (${uid(m.id)}, ${uid(m.manufacturerId)}, ${q(m.slug)}, ${q(m.name)});`);
for (const [key, d] of Object.entries(derivatives)) {
  const modelId = `md-${makeSlugForKey(key)}-${slugify(d[0])}`;
  sql.push(`insert into public.derivatives (id, model_id, name, fuel_type, transmission, body_type, engine_cc, power_bhp, doors, seats, insurance_group) values (${uid(`dv-${key}`)}, ${uid(modelId)}, ${q(d[1])}, ${q(d[2])}, ${q(d[3])}, ${q(d[4])}, ${d[5] == null ? "null" : Math.round(d[5] * 1000)}, ${d[6]}, ${d[7]}, ${d[8]}, ${d[9]}) on conflict (model_id, name) do nothing;`);
}
equipmentCatalogue.forEach((e, i) => sql.push(`insert into public.equipment_items (id, slug, name, category) values (${i + 1}, ${q(e.slug)}, ${q(e.name)}, ${q(e.category)});`));
sql.push(`select setval('public.equipment_items_id_seq', ${equipmentCatalogue.length});`);

for (const d of dealerships) {
  sql.push(`insert into public.dealerships (id, slug, name, description, phone, is_verified, is_featured, is_demo, brand_color) values (${uid(d.id)}, ${q(d.slug)}, ${q(d.name)}, ${q(d.description)}, ${q(d.phone)}, ${d.verified}, ${d.featured}, true, ${q(d.logoColor)});`);
  sql.push(`insert into public.dealership_locations (id, dealership_id, name, address_line1, town, county, postcode, lat, lng, opening_hours, is_primary) values (${uid(`loc-${d.id}`)}, ${uid(d.id)}, 'Main site', 'Demo address', ${q(d.location.town)}, ${q(d.location.county)}, ${q(d.location.postcode)}, ${d.location.lat}, ${d.location.lng}, ${q(JSON.stringify(d.openingHours))}::jsonb, true);`);
  sql.push(`insert into public.dealership_staff (dealership_id, user_id, role) values (${uid(d.id)}, ${uid(`user-${d.id}`)}, 'owner');`);
  sql.push(`insert into public.user_roles (user_id, role) values (${uid(`user-${d.id}`)}, 'dealer_staff') on conflict do nothing;`);
  // Demo reviews that reproduce the displayed rating (clearly flagged is_demo).
  if (d.rating) {
    const stars = [5, 5, 4, 5, 4].map((s, i) => (i === 4 && d.rating! < 4.6 ? 3 : s));
    stars.forEach((s, i) => sql.push(`insert into public.reviews (dealership_id, rating, title, body, status, is_demo) values (${uid(d.id)}, ${s}, 'Demo review', 'Demonstration review content.', 'published', true);`));
  }
}

for (const v of demoVehicles) {
  const vid = uid(`veh-${v.id}`), aid = uid(v.id);
  const sellerUser = v.sellerType === "private" ? uid(`user-${v.id}`) : "null";
  sql.push(`insert into public.vehicles (id, vrm, manufacturer_id, model_id, derivative_text, year, plate_identifier, fuel_type, transmission, body_type, engine_cc, power_bhp, colour, doors, seats, insurance_group, ulez_compliant, write_off_category, owners, created_by, dealership_id) values (` +
    `${vid}, ${q(v.registration)}, ${uid(v.manufacturerId)}, ${uid(v.modelId)}, ${q(v.derivative)}, ${v.year}, ${q(v.registrationYearLabel.match(/\((\d+) reg\)/)?.[1] ?? null)}, ${q(v.fuelType)}, ${q(v.transmission)}, ${q(v.bodyType)}, ` +
    `${v.engineSizeLitres == null ? "null" : Math.round(v.engineSizeLitres * 1000)}, ${v.enginePowerBhp}, ${q(v.colour)}, ${v.doors}, ${v.seats}, ${v.insuranceGroup}, ${v.ulezCompliant}, ${q(v.writeOffCategory)}, ${v.owners}, ` +
    `${v.sellerType === "private" ? sellerUser : uid(`user-${v.dealershipId}`)}, ${v.dealershipId ? uid(v.dealershipId) : "null"});`);
  sql.push(`insert into public.vehicle_specifications (vehicle_id, co2_g_km, mpg_combined, electric_range_miles, battery_kwh, annual_tax_gbp, acceleration_0_62, top_speed_mph, source) values (${vid}, ${q(v.co2GPerKm)}, ${q(v.mpgCombined)}, ${q(v.electricRangeMiles)}, ${q(v.batteryKwh)}, ${v.annualTaxGbp}, ${q(v.acceleration0to62)}, ${q(v.topSpeedMph)}, 'demo');`);
  for (const e of v.equipment) sql.push(`insert into public.vehicle_equipment (vehicle_id, equipment_id) values (${vid}, ${equipmentCatalogue.findIndex((c) => c.slug === e) + 1});`);
  const firstPrice = v.previousPrice ?? v.price;
  sql.push(`insert into public.advertisements (id, slug, vehicle_id, seller_type, seller_user_id, dealership_id, dealership_location_id, status, is_featured, is_demo, title, description, price_gbp, mileage, service_history, condition, postcode, town, county, lat, lng, views_count, saves_count, published_at, expires_at) values (` +
    `${aid}, ${q(v.slug)}, ${vid}, ${q(v.sellerType)}, ${sellerUser}, ${v.dealershipId ? uid(v.dealershipId) : "null"}, ${v.dealershipId ? uid(`loc-${v.dealershipId}`) : "null"}, 'active', ${v.featured}, true, ` +
    `${q(`${v.make} ${v.model} ${v.derivative}`)}, ${q(v.description)}, ${firstPrice}, ${v.mileage}, ${q(v.serviceHistory)}, ${q(v.condition)}, ${q(v.location.postcode)}, ${q(v.location.town)}, ${q(v.location.county)}, ${v.location.lat.toFixed(5)}, ${v.location.lng.toFixed(5)}, ${v.views}, ${v.saves}, ${q(v.listedAt)}, ${q(new Date(new Date(v.listedAt).getTime() + 28 * 864e5).toISOString())});`);
  if (v.previousPrice) sql.push(`update public.advertisements set price_gbp = ${v.price} where id = ${aid};`);
  v.images.forEach((img, i) => sql.push(`insert into public.vehicle_media (advertisement_id, kind, storage_path, width, height, alt, position, is_primary) values (${aid}, 'photo', ${q(`demo:${img.src}`)}, ${img.width}, ${img.height}, ${q(img.alt)}, ${i}, ${i === 0});`));
}
sql.push("commit;", `-- reference date ${DEMO_REFERENCE_DATE.toISOString()} · ${demoVehicles.length} demo listings`);
mkdirSync(join(root, "supabase"), { recursive: true });
writeFileSync(join(root, "supabase/seed.sql"), sql.join("\n") + "\n");

// Illustrative renders
const outDir = join(root, "public/demo-vehicles");
mkdirSync(outDir, { recursive: true });
const combos = new Set(demoVehicles.map((v) => `${v.bodyType}|${v.colour.toLowerCase()}|${v.make} ${v.model}`));
let files = 0;
for (const c of combos) {
  const [body, colour, label] = c.split("|") as [typeof demoVehicles[number]["bodyType"], string, string];
  for (const variant of [0, 1, 2, 3] as ArtVariant[]) {
    writeFileSync(join(outDir, `${body}-${colour}-${variant}.svg`), renderVehicleSvg(body, colour, variant, `${colour} ${body}`));
    files++;
  }
  void label;
}
writeFileSync(join(outDir, "hero-suv.svg"), renderVehicleSvg("suv", "blue", 1, "Illustrative SUV", { transparent: true }));
console.log(`seed.sql: ${demoVehicles.length} listings · ${new Set([...combos].map((c) => c.split("|").slice(0, 2).join("|"))).size * 4} illustrative render files`);
